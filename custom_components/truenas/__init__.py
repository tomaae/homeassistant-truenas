"""The TrueNAS integration."""

from __future__ import annotations


from homeassistant.core import HomeAssistant
from homeassistant.config_entries import ConfigEntry
from homeassistant.helpers import entity_registry as er

from .const import (
    DOMAIN,
    PLATFORMS,
)
from .coordinator import TrueNASCoordinator


# ---------------------------
#   update_listener
# ---------------------------
async def _async_update_listener(hass: HomeAssistant, entry: ConfigEntry):
    """Handle options update."""
    await hass.config_entries.async_reload(entry.entry_id)


# ---------------------------
#   async_setup_entry
# ---------------------------
async def async_setup_entry(hass: HomeAssistant, config_entry: ConfigEntry) -> bool:
    """Set up TrueNAS config entry."""
    _async_fix_trailing_underscore_entity_ids(hass, config_entry)
    coordinator = TrueNASCoordinator(hass, config_entry)
    await coordinator.async_config_entry_first_refresh()
    hass.data.setdefault(DOMAIN, {})[config_entry.entry_id] = coordinator
    await hass.config_entries.async_forward_entry_setups(config_entry, PLATFORMS)
    config_entry.async_on_unload(config_entry.add_update_listener(async_reload_entry))
    return True


# ---------------------------
#   _async_fix_trailing_underscore_entity_ids
# ---------------------------
def _async_fix_trailing_underscore_entity_ids(
    hass: HomeAssistant, config_entry: ConfigEntry
) -> None:
    """Rename entity IDs that unnamed entities were registered with, such as update.truenas_system_.

    A trailing underscore is invalid and can't be entered by a user, so these IDs
    were always generated by the integration and are safe to rename. If the corrected
    ID is taken, the next free numbered ID is used, so no invalid ID is left behind.
    """
    ent_reg = er.async_get(hass)
    for entry in er.async_entries_for_config_entry(ent_reg, config_entry.entry_id):
        if not entry.entity_id.endswith("_"):
            continue
        base = entry.entity_id.rstrip("_")
        new_entity_id = base
        suffix = 2
        # If the corrected ID is taken, number it the way Home Assistant does
        while ent_reg.async_get(new_entity_id) or hass.states.get(new_entity_id):
            new_entity_id = f"{base}_{suffix}"
            suffix += 1
        ent_reg.async_update_entity(entry.entity_id, new_entity_id=new_entity_id)


# ---------------------------
#   async_reload_entry
# ---------------------------
async def async_reload_entry(hass: HomeAssistant, config_entry: ConfigEntry) -> None:
    """Reload the config entry when it changed."""
    await hass.config_entries.async_reload(config_entry.entry_id)


# ---------------------------
#   async_unload_entry
# ---------------------------
async def async_unload_entry(hass: HomeAssistant, config_entry: ConfigEntry) -> bool:
    """Unload TrueNAS config entry."""

    if unload_ok := await hass.config_entries.async_unload_platforms(
        config_entry, PLATFORMS
    ):
        hass.data[DOMAIN].pop(config_entry.entry_id)

    return unload_ok
